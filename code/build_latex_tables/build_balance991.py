"""Build the ITT (991) balance table from the reproducible CSVs written by
build_balance991.do. Baseline covariates by the woman's RANDOMLY ASSIGNED
first-visit counselor, over the approached (intention-to-treat) population.

Reads:  Analysis/tables/balance991.csv, Analysis/tables/balance991_meta.csv
Writes: Main paper/CQ_manuscript/tables/table2_balance.tex  (the active manuscript)
        Analysis/tables/table2_balance.tex   (label tab:balance_couns_main)
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
ANALYSIS = os.path.abspath(os.path.join(HERE, "..", ".."))
CSV  = os.path.join(ANALYSIS, "tables", "balance991.csv")
META = os.path.join(ANALYSIS, "tables", "balance991_meta.csv")
OUTS = [
    os.path.join(ANALYSIS, "..", "Main paper", "CQ_manuscript", "tables", "table2_balance.tex"),
    os.path.join(ANALYSIS, "tables", "table2_balance.tex"),
]

rows = {r["rowkey"]: r for r in csv.DictReader(open(CSV))}
meta = {r["stat"]: r["value"] for r in csv.DictReader(open(META))}

# (rowkey, display label, indented-under-area-header)
ROWDEFS = [
    ("age1", r"Age $\leq$20", False), ("age2", "Age 21--25", False),
    ("age3", "Age 26--30", False), ("age4", "Age 31--35", False),
    ("sex_age_bl", "Age at first sex", False), ("total_alive_bl", "Children alive", False),
    ("ever_use_bl", "FP ever use", False), ("edu_primary_bl", "Education: primary+", False),
    ("work_bl", "Working", False), ("religion_r_bl", "Religion (Christian)", False),
    ("__AREA__", None, False),
    ("area7", "Area 7", True), ("area8", "Area 8", True), ("area23", "Area 23", True),
    ("area24", "Area 24", True), ("area50", "Area 50", True), ("area51", "Area 51", True),
    ("area56", "Area 56", True),
    ("ethnicity_r_bl", "Ethnicity (Chewa)", False), ("preg_2016", "Pregnant at BL", False),
    ("curr_use_bl", "Current FP use", False), ("counselLP_bl", "Counseled last preg", False),
]

def cell(r, c):  # mean for counselor c (1-6) or 'tot' (SDs dropped per committee feedback)
    return r["mtot"] if c == "tot" else r["m" + c]

def srow(rk, label, indent):
    r = rows[rk]
    lab = (r"\quad " + label) if indent else label
    cells = " & ".join(cell(r, c) for c in ["1", "2", "3", "4", "5", "6", "tot"])
    return f"{lab:<24} & {cells} & {r['F']} & {r['p']} \\\\"

o = []
o.append(r"% Table: ITT (991) Balance -- baseline covariates by randomly assigned first-visit counselor")
o.append(r"% Auto-generated by build_balance991.py from balance991.csv + balance991_meta.csv")
o.append(r"\begin{adjustwidth}{-0.75in}{-0.75in}")
o.append(r"\begin{table}[H]")
o.append(r"\centering")
o.append(r"\caption{Balance: Baseline Covariates by Randomly Assigned Counselor (Intention-to-Treat Sample)}")
o.append(r"\label{tab:balance_couns_main}")
o.append(r"\small")
o.append(r"\setlength{\tabcolsep}{6pt}")
o.append(r"\renewcommand{\arraystretch}{0.92}")
o.append(r"\begin{tabular}{lccccccccc}")
o.append(r"\toprule")
o.append(r" & \multicolumn{6}{c}{Counselor} & & \multicolumn{2}{c}{ANOVA} \\")
o.append(r"\cmidrule(lr){2-7} \cmidrule(lr){9-10}")
o.append(r"Covariate & 1 & 2 & 3 & 4 & 5 & 6 & Total & F & p \\")
o.append(r"\midrule")
for rk, label, indent in ROWDEFS:
    if rk == "__AREA__":
        o.append(r"\addlinespace[2pt]")
        o.append(r"\multicolumn{10}{l}{\textit{Neighborhood area indicators$^a$}} \\")
        continue
    o.append(srow(rk, label, indent))
    if rk == "area56":
        o.append(r"\addlinespace[2pt]")
o.append(r"\midrule")
nr = rows["N"]
o.append(r"$N$                      & %s & %s & %s & %s & %s & %s & %s & & \\" % (
    nr["m1"], nr["m2"], nr["m3"], nr["m4"], nr["m5"], nr["m6"], nr["mtot"]))
o.append(r"\bottomrule")
o.append(r"\end{tabular}")
o.append(r"")
o.append(r"\smallskip")
o.append(r"\begin{minipage}{\linewidth}")
o.append(
    r"\scriptsize\textit{Notes:} Mean of each baseline covariate "
    r"in the control set $X_i$, by the woman's randomly assigned first-visit counselor, over the $982$ "
    r"approached (intention-to-treat) women whose counselor is one of the six. The ANOVA columns test "
    r"equality of means across the six counselors; none is significant at $5$ percent. $^a$Area-by-counselor "
    r"independence: $\chi^2(%s) = %s$, $p = %s$. A heteroskedasticity-robust regression of the "
    r"counselor-level CQT on the full covariate set does not reject the joint null that all coefficients "
    r"are zero ($F(%s, %s) = %s$, $p = %s$, $N = %s$)." % (
        meta["area_chi2_df"], meta["area_chi2"], meta["area_chi2_p"],
        meta["cqt_orth_df1"], meta["cqt_orth_df2"], meta["cqt_orth_F"],
        meta["cqt_orth_p"], meta["cqt_orth_N"]))
o.append(r"\end{minipage}")
o.append(r"\end{table}")
o.append(r"\end{adjustwidth}")

text = "\n".join(o) + "\n"
for p in OUTS:
    with open(os.path.abspath(p), "w") as fh:
        fh.write(text)
    print("Wrote", os.path.abspath(p))
