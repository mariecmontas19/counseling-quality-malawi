#!/usr/bin/env python3
"""
build_takeup_balance.py

Builds the CQT-on-take-up balance appendix table from the Stata output
/tmp/cqt_takeup_balance.csv (produced by dofile/results_takeup_balance.do).

Input  : /tmp/cqt_takeup_balance.csv  (outcome,beta,se,p,n,meandv)
Output : tables/cqt_takeup_balance.tex   (label tab:cqt_takeup_balance)

Run from the Analysis/ directory:  python3 dofile/build_latex_tables/build_takeup_balance.py
"""
import csv

IN  = "/tmp/cqt_takeup_balance.csv"
OUT = "tables/cqt_takeup_balance.tex"

LABELS = {
    "received_transport":      "Transport voucher",
    "received_reimbursement":  "Clinic reimbursement",
    "received_any_ancillary":  "Any ancillary component",
}
ORDER = ["received_transport", "received_reimbursement", "received_any_ancillary"]


def stars(p):
    if p < 0.01:
        return "$^{***}$"
    if p < 0.05:
        return "$^{**}$"
    if p < 0.10:
        return "$^{*}$"
    return ""


rows = {}
with open(IN) as f:
    for r in csv.DictReader(f):
        rows[r["outcome"]] = r

body = []
for key in ORDER:
    r = rows[key]
    b   = float(r["beta"])
    se  = float(r["se"])
    p   = float(r["p"])
    n   = int(float(r["n"]))
    mdv = float(r["meandv"])
    body.append(
        f"{LABELS[key]:<24s} & {b:0.3f}{stars(p)} & ({se:0.3f}) & "
        f"{p:0.3f} & {mdv:0.3f} & {n} \\\\"
    )

tex = r"""% CQT-on-take-up balance table. Auto-generated by build_takeup_balance.py.
\begin{table}[H]
\centering
\caption{Balance: CQT Instrument and Ancillary-Component Take-Up}
\label{tab:cqt_takeup_balance}
\small
\setlength{\tabcolsep}{8pt}
\renewcommand{\arraystretch}{1.1}
\begin{tabular}{lccccc}
\toprule
Ancillary component & CQT coef. & Robust SE & $p$-value & Mean & $N$ \\
\midrule
""" + "\n".join(body) + r"""
\bottomrule
\end{tabular}

\smallskip
\begin{minipage}{0.92\linewidth}
\footnotesize \textit{Notes:} Each row reports an OLS regression of an ancillary-component take-up indicator on the range-normalized Counselor Quality Tendency (CQT) instrument (satisfaction-and-topics specification) and the full baseline covariate set $X_i$, estimated on the endline treatment sample (year 2018). The CQT coefficient is the change in take-up associated with moving from the lowest to the highest counselor-quality tendency. \emph{Transport voucher} and \emph{Clinic reimbursement} indicate any use of the free-taxi and clinic-reimbursement components respectively; \emph{Any ancillary component} is their union. Take-up of these components is a \emph{post-treatment} outcome that may itself be shifted by counseling quality, so it is not conditioned on in the main specification (Section~\ref{ssec:threats}); Appendix Tables~\ref{tab:iv_robust_takeup_mech} and~\ref{tab:iv_robust_takeup_outc} show the IV estimates are robust to controlling for it. Heteroskedasticity-robust (HC3) standard errors in parentheses. Stars: $^{*}$ p$<$0.10, $^{**}$ p$<$0.05, $^{***}$ p$<$0.01.
\end{minipage}
\end{table}
"""

with open(OUT, "w") as f:
    f.write(tex)
print(f"Wrote {OUT}")
