"""Build the counselor topic-coverage table (Appendix Table A5) from the
reproducible per-counselor CSV written by build_topic_coverage.do.

Reads:  tables/counselor_topic_analysis.csv  (rows couns_id 0=Overall, 1-6)
Writes: Main paper/JHE submission/tables/table6_topic_coverage.tex
        Analysis/tables/table6_topic_coverage.tex
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
ANALYSIS = os.path.abspath(os.path.join(HERE, "..", ".."))
CSV = os.path.join(ANALYSIS, "tables", "counselor_topic_analysis.csv")
OUTS = [
    os.path.join(ANALYSIS, "..", "Main paper", "JHE submission", "tables", "table6_topic_coverage.tex"),
    os.path.join(ANALYSIS, "tables", "table6_topic_coverage.tex"),
]

rows = {int(float(r["couns_id"])): r for r in csv.DictReader(open(CSV))}
order = [1, 2, 3, 4, 5, 6, 0]        # counselors 1-6 then Overall

TOPICS = [
    ("share_t_methods",  "FP methods"),
    ("share_t_preg",     "Pregnancy"),
    ("share_t_spacing",  "Birth spacing"),
    ("share_t_sidefx",   "Side effects of FP"),
    ("share_t_services", "FP services"),
    ("share_t_sti",      "STI prevention"),
    ("share_t_partner",  "Partner involvement"),
    ("share_t_child",    "Child health"),
    ("share_t_breast",   "Breastfeeding"),
]

def f3(cid, col):
    return f"{float(rows[cid][col]):.3f}"

def srow(label, col):
    cells = " & ".join(f3(c, col) for c in order)
    return f"{label:<20} & {cells} \\\\"

def f2_or_dash(cid, col):
    v = rows[cid][col]
    return "---" if v in ("", ".", "NA") else f"{float(v):.2f}"

def int_or_dash(cid, col):
    v = rows[cid][col]
    if v in ("", ".", "NA"):
        return "---"
    n = int(round(float(v)))
    return f"{n:,}".replace(",", "{,}") if n >= 1000 else str(n)

out = []
out.append(r"% Table 6: Counseling Topic Coverage by Counselor")
out.append(r"% Auto-generated by build_topic_coverage.py from counselor_topic_analysis.csv")
out.append(r"\begin{table}[H]")
out.append(r"\centering")
out.append(r"\caption{Counseling Topic Coverage by Counselor: Session-Level Descriptive Statistics}")
out.append(r"\label{tab:topic_couns_main}")
out.append(r"\small")
out.append(r"\begin{adjustbox}{max width=\textwidth}")
out.append(r"\begin{tabular}{lccccccc}")
out.append(r"\toprule")
out.append(r" & \multicolumn{6}{c}{Counselor} & \\")
out.append(r"\cmidrule(lr){2-7}")
out.append(r"Topic share & 1 & 2 & 3 & 4 & 5 & 6 & Overall \\")
out.append(r"\midrule")
out.append(r"\multicolumn{8}{l}{\textit{Panel A: Topic coverage (share of sessions)}} \\[3pt]")
for col, lab in TOPICS:
    out.append(srow(lab, col))
out.append(r"\midrule")
out.append(r"\multicolumn{8}{l}{\textit{Panel B: Summary measures}} \\[3pt]")
out.append("Mean topics/session  & " + " & ".join(f2_or_dash(c, "avg_n_topics_couns") for c in order) + r" \\")
out.append("Topic breadth (0--9) & " + " & ".join(int_or_dash(c, "topic_breadth") for c in order) + r" \\")
out.append("Mean minutes/session & " + " & ".join(f2_or_dash(c, "mean_minutes") for c in order) + r" \\")
out.append("Herfindahl index     & " + " & ".join(f2_or_dash(c, "topic_herfindahl") for c in order) + r" \\")
out.append("$N$ sessions         & " + " & ".join(int_or_dash(c, "n_sessions") for c in order) + r" \\")
out.append(r"\bottomrule")
out.append(r"\end{tabular}")
out.append(r"\end{adjustbox}")
out.append("")
out.append(r"\medskip")
out.append(
    r"\parbox{\textwidth}{\scriptsize\textit{Notes:} Each cell in Panel~A reports the share of "
    r"sessions where the topic was discussed, by the counselor who conducted the session (not "
    r"restricted to first session), across all $3{,}898$ counseling sessions with a valid recorded "
    r"session length. Panel~B reports summary measures. Topic breadth = number of distinct topics "
    r"the counselor ever covers (out of 9). Herfindahl index $=\sum_{k=1}^{9}\tilde{s}_k^2$, where "
    r"$\tilde{s}_k=s_k/\sum_j s_j$ is topic $k$'s share of the counselor's total topic coverage, "
    r"normalized so the shares sum to one; higher values indicate that coverage concentrates on "
    r"fewer topics. Counselor~6 (highest CQT) has the lowest concentration, spreading attention "
    r"nearly evenly across topics, whereas Counselor~4 (lower CQT) is the most concentrated, "
    r"focusing on a narrower set of topics.}")
out.append(r"\end{table}")

text = "\n".join(out) + "\n"
for p in OUTS:
    with open(os.path.abspath(p), "w") as fh:
        fh.write(text)
    print("Wrote", os.path.abspath(p))
