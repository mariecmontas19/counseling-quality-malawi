"""Build the observation-count appendix table from build_obs_summary.do output.
Replaces the outdated tab:obs_summary. Estimation N matches the N rows in
tab:iv_main (verified). Reads Analysis/tables/obs_summary.csv. Writes
tables/obs_summary.tex (both JHE + Analysis copies), label tab:obs_summary.

"Collected at BL?" is set per verified variable provenance (wave-pattern check in
build_obs_summary.do log + variable type): Yes = baseline (2016) survey item;
No = administrative reimbursement-log or a construct from post-baseline events
(constant within woman across waves); NA = derived from program counseling
sessions (no pre-program analogue).
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
ANALYSIS = os.path.abspath(os.path.join(HERE, "..", ".."))
CSV = os.path.join(ANALYSIS, "tables", "obs_summary.csv")
OUTS = [
    os.path.join(ANALYSIS, "..", "Main paper", "JHE submission", "tables", "obs_summary.tex"),
    os.path.join(ANALYSIS, "tables", "obs_summary.tex"),
]

rows = {r["rowkey"]: r for r in csv.DictReader(open(CSV))}

PANELS = [
    ("Panel A: Counseling continuity (woman level)", [
        ("share_same_counselor", "Share of sessions with same counselor", "N/A"),
        ("total_sessions",       "Total counseling sessions",            "N/A"),
        ("visit_rate_mo",        "Visit rate per month",                 "N/A"),
        ("husband_present",      "Husband present at session",           "N/A"),
    ]),
    ("Panel B: Topic requested after the first session (woman level)", [
        ("etp1_fp",          "Family planning",        "N/A"),
        ("etp1_spacing",     "Birth spacing",          "N/A"),
        ("etp1_preg",        "Pregnancy",              "N/A"),
        ("etp1_partner",     "Partner / relationship", "N/A"),
        ("etp1_childhealth", "Child health",           "N/A"),
        ("etp1_breast",      "Breastfeeding",          "N/A"),
    ]),
    ("Panel C: Family planning coverage (2018 endline)", [
        ("admin_fp_any",        "Any FP service (administrative log)",   "No"),
        ("admin_inject_any",    "Any injectable (administrative log)",   "No"),
        ("n_admin_fp",          "Number of FP services (admin.\\ log)",  "No"),
        ("fp_inj_coverage_frac","Injectable coverage fraction",         "No"),
        ("husband_knows_fp",    "Husband knows of FP use",              "Yes"),
    ]),
    ("Panel D: Reproductive outcomes (2018 endline)", [
        ("birth_within_24mo",   "Birth within 24 months",        "No"),
        ("preg_within_12mo",    "Pregnancy within 12 months",    "No"),
        ("preg_within_24mo",    "Pregnancy within 24 months",    "No"),
        ("mistimed_preg_expost","Mistimed pregnancy (ex post)",  "No"),
    ]),
]

def comma(n):
    return f"{int(n):,}".replace(",", "{,}")

o = []
o.append(r"% Observation counts by outcome -- auto-generated by build_obs_summary.py")
o.append(r"% Estimation N matches the N rows in tab:iv_main (verified).")
o.append(r"\begin{table}[H]")
o.append(r"\centering")
o.append(r"\caption{Observation Counts by Outcome}")
o.append(r"\label{tab:obs_summary}")
o.append(r"\small")
o.append(r"\begin{adjustbox}{max width=\textwidth}")
o.append(r"\begin{tabular}{lccccc}")
o.append(r"\toprule")
o.append(r"Outcome & Non-missing & Missing & Covariate & Estimation & Collected \\")
o.append(r"        & $N$         & $N$     & loss$^a$  & $N$        & at BL?    \\")
o.append(r"\midrule")
for ptitle, items in PANELS:
    o.append(r"\multicolumn{6}{l}{\textit{%s}} \\" % ptitle)
    for rk, label, bl in items:
        r = rows[rk]
        o.append(r"%s & %s & %s & %s & %s & %s \\" % (
            label, comma(r["nonmiss"]), comma(r["missing"]),
            comma(r["covloss"]), comma(r["estN"]), bl))
    o.append(r"\midrule" if (ptitle, items) != PANELS[-1] else r"\bottomrule")
o.append(r"\end{tabular}")
o.append(r"\end{adjustbox}")
o.append(r"")
o.append(r"\medskip")
o.append(r"\footnotesize")
o.append(
    r"\textit{Notes:} Eligible sample: all treatment-arm women (woman level, $N = 1{,}027$) for "
    r"Panels A--B, and treatment women at the 2018 endline ($N = 782$) for Panels C--D. Missing $N$ "
    r"= eligible minus non-missing. Estimation $N$ is the pooled IV sample and matches the $N$ rows "
    r"of Tables~\ref{tab:iv_mechanism} and~\ref{tab:iv_outcomes}; $^a$covariate loss = non-missing minus estimation $N$ (missing "
    r"baseline covariates, plus the few Panel A--B women without a defined instrument). "
    r"``Collected at BL?'': Yes = 2016 survey item (\emph{husband knows of FP use} is asked only of "
    r"FP users, hence the smaller $N$); No = administrative or post-baseline construct; N/A = "
    r"session-derived.")
o.append(r"\end{table}")

text = "\n".join(o) + "\n"
for p in OUTS:
    with open(os.path.abspath(p), "w") as fh:
        fh.write(text)
    print("Wrote", os.path.abspath(p))
