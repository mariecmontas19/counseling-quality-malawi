"""Build the combined cost-effectiveness table from the reproducible CSVs written
by build_cea_costs.py. Layout: Panel A (program cost, tall/narrow) on the LEFT;
the RIGHT column stacks Panel B (couple-years of protection delivered) above
Panel C (counselor throughput by quality, transposed). One float, label tab:cea.

Scope (Mahesh, 2026-06-23): counseling component only. Field managers counted for
12 months (the window they worked with counselors); the FP-service reimbursement
is EXCLUDED from cost (it is a commodity outlay), and participant transport is
excluded. The reimbursement service log is still the record from which Panel B's
CYP (the protection output) is computed.

Reads:  Analysis/CEA/outputs/cea_cost_table.csv
        Analysis/CEA/outputs/cea_per_method.csv
        Analysis/CEA/outputs/cea_metrics.csv
        Analysis/CEA/outputs/cea_throughput.csv
Writes: Main paper/JHE submission/tables/cea_combined.tex
        Analysis/tables/cea_combined.tex

Dose-reduction stars ($^{**}$, both p<0.05) verified against tab:iv_main
(total sessions pooled -0.422**, postpartum -0.623**).
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
ANALYSIS = os.path.abspath(os.path.join(HERE, "..", ".."))
OUTDIR   = os.path.join(ANALYSIS, "CEA", "outputs")
COST_CSV = os.path.join(OUTDIR, "cea_cost_table.csv")
PM_CSV   = os.path.join(OUTDIR, "cea_per_method.csv")
MET_CSV  = os.path.join(OUTDIR, "cea_metrics.csv")
THRU_CSV = os.path.join(OUTDIR, "cea_throughput.csv")
OUTS = [
    os.path.join(ANALYSIS, "..", "Main paper", "JHE submission", "tables", "cea_combined.tex"),
    os.path.join(ANALYSIS, "tables", "cea_combined.tex"),
]

def money(x):
    return f"{x:,.0f}".replace(",", "{,}")

# ---------- Panel A: program cost (counseling component only) ----------
def grp(name):
    n = name.lower()
    if "trainer" in n or "per diem" in n: return "training"
    if "field manager" in n:              return "field"
    return "counselor"

GROUP_TITLE = {"counselor": "Counselor compensation \\& field",
               "training":  "Counselor training",
               "field":     "Field supervision"}
GROUP_ORDER = ["counselor", "training", "field"]
DISPLAY = {
    "Counselor salary (6 counselors, 10 mo initial)":   "Counselor salaries (initial)",
    "Counselor phone credit (initial)":                 "Phone credit (initial)",
    "Counselor transport: van rental + fuel (initial)": "Transport: van + fuel (initial)",
    "Counselor materials":                              "Counseling materials",
    "Counselor salary (6 counselors, 2 mo extension)":  "Counselor salaries (extension)",
    "Counselor phone credit (extension)":               "Phone credit (extension)",
    "Counselor transport (extension)":                  "Transport (extension)",
    "MOH-RHD trainer (FP/RH content)":                  "Ministry of Health trainer",
    "Counselor training per diem":                      "Training per diem",
}

crows, total, per_woman = [], None, None
for r in csv.DictReader(open(COST_CSV)):
    name, usd = r["component"], r["usd"]
    if name.startswith("TOTAL"):              total = float(usd)
    elif name.startswith("Cost per treated"): per_woman = float(usd)
    else:                                     crows.append((name, float(usd)))

cgroups = {g: [] for g in GROUP_ORDER}
for name, usd in crows:
    g = grp(name)
    lab = "Field-manager salaries (12 mo)" if g == "field" else DISPLAY.get(name, name)
    cgroups[g].append((lab, usd))

# ---------- Panel B: couple-years of protection (CYP) ----------
pm = {r["method"]: r for r in csv.DictReader(open(PM_CSV))}
met = {r["metric"]: r["value"] for r in csv.DictReader(open(MET_CSV))}
total_cyp    = float(met["total_cyp"])
cost_per_cyp = float(met["cost_per_cyp"])

CYP_ROWS = [  # (method key, display, factor display)
    ("Injectable",    "Injectable (DMPA)",     "0.25"),
    ("Implant",       "Implant (Jadelle)",     "3.8"),
    ("IUD",           "Copper IUD",            "4.6"),
    ("Sterilization", "Female sterilization",  "10.0"),
    ("Pills",         "Oral pills",            "0.0667"),
]

# ---------- Panel C: throughput, transposed ----------
thr = {r["scenario"]: r for r in csv.DictReader(open(THRU_CSV))}
REF, POOL, PP = thr["Mean counseling dose (reference)"], thr["pooled"], thr["postpartum"]
def f2(x): return f"{float(x):.2f}"
def f1(x): return f"{float(x):.1f}"
def pct(r): return "---" if r["pct_gain"] == "" else r"$+%.1f\%%$" % float(r["pct_gain"])
def dred(r): return "---" if r["dose_reduction"] == "" else r"$%.2f^{**}$" % float(r["dose_reduction"])

# ---------- assemble ----------
o = []
o.append(r"% Combined cost-effectiveness table (Panel A cost | Panels B CYP + C throughput)")
o.append(r"% Auto-generated by build_cea_combined.py")
o.append(r"\begin{table}[H]")
o.append(r"\centering")
o.append(r"\caption{Cost-Effectiveness of the Counseling Program (Provider Perspective)}")
o.append(r"\label{tab:cea}")
o.append(r"\small")

# ----- LEFT minipage: Panel A (cost) -----
o.append(r"\begin{minipage}[t]{0.46\textwidth}")
o.append(r"\centering")
o.append(r"\textit{Panel A: Program cost (2016--2018 USD)}\\[3pt]")
o.append(r"\begin{tabular}{lr}")
o.append(r"\toprule")
o.append(r"Cost component & USD \\")
o.append(r"\midrule")
for g in GROUP_ORDER:
    items = cgroups[g]
    if not items:
        continue
    o.append(r"\multicolumn{2}{l}{\textit{%s}} \\" % GROUP_TITLE[g])
    for lab, usd in items:
        o.append(r"\quad %s & %s \\" % (lab, money(usd)))
    if len(items) > 1:
        o.append(r"\quad Subtotal & %s \\[2pt]" % money(sum(u for _, u in items)))
    else:
        o.append(r"\addlinespace[2pt]")
o.append(r"\midrule")
o.append(r"\textbf{Total program cost} & \textbf{%s} \\" % money(total))
o.append(r"Cost per treated woman ($N{=}1{,}027$) & %.2f \\" % per_woman)
o.append(r"\bottomrule")
o.append(r"\end{tabular}")
o.append(r"\end{minipage}%")
o.append(r"\hfill")

# ----- RIGHT minipage: Panel B (CYP) then Panel C (throughput) -----
o.append(r"\begin{minipage}[t]{0.51\textwidth}")
o.append(r"\centering")
o.append(r"\textit{Panel B: Couple-years of protection (CYP) delivered}\\[3pt]")
o.append(r"\begin{tabular}{lccc}")
o.append(r"\toprule")
o.append(r"Method & Services & CYP/unit & CYP \\")
o.append(r"\midrule")
for key, disp, fac in CYP_ROWS:
    cyp = float(pm[key]["cyp"])
    n = int(round(cyp / float(fac)))
    o.append(r"%s & %d & %s & %.1f \\" % (disp, n, fac, cyp))
o.append(r"\midrule")
o.append(r"\textbf{Total CYP} & & & \textbf{%.1f} \\" % total_cyp)
o.append(r"Cost per CYP (USD) & & & %.0f \\" % round(cost_per_cyp))
o.append(r"\bottomrule")
o.append(r"\end{tabular}")

o.append(r"\par\medskip")
o.append(r"\textit{Panel C: Counselor throughput by quality}\\[3pt]")
o.append(r"\begin{tabular}{lccc}")
o.append(r"\toprule")
o.append(r" & Mean & \multicolumn{2}{c}{Higher quality} \\")
o.append(r"\cmidrule(lr){3-4}")
o.append(r" & dose & Pooled & Postp. \\")
o.append(r"\midrule")
o.append(r"Sessions per woman & %s & %s & %s \\" % (f2(REF["dose"]), f2(POOL["dose"]), f2(PP["dose"])))
o.append(r"Dose reduction (IV) & --- & %s & %s \\" % (dred(POOL), dred(PP)))
o.append(r"Women per couns.-month & %s & %s & %s \\" % (f1(REF["women_per_cm"]), f1(POOL["women_per_cm"]), f1(PP["women_per_cm"])))
o.append(r"Change vs.\ reference & --- & %s & %s \\" % (pct(POOL), pct(PP)))
o.append(r"Counselor cost/woman & %s & %s & %s \\" % (f2(REF["cost_per_woman"]), f2(POOL["cost_per_woman"]), f2(PP["cost_per_woman"])))
o.append(r"\bottomrule")
o.append(r"\end{tabular}")
o.append(r"\end{minipage}")

# ----- shared notes -----
o.append(r"")
o.append(r"\par\smallskip")
o.append(
    r"\begin{minipage}{0.97\linewidth}\footnotesize\textit{Notes:} Provider-perspective cost of the "
    r"counseling component only \citep{dhaliwal2013comparative}; participant time, participant transport, "
    r"and contraceptive commodities are excluded. \textit{Panel A:} counselor and field-manager salaries, "
    r"training, transport, and materials over the twelve-month counseling window; field managers are "
    r"counted for the twelve months they worked alongside the counselors. \textit{Panel B:} couple-years "
    r"of protection from the family-planning services women obtained through the program, converted at "
    r"standard factors \citep{usaid2022cyp}; the service log records only program-channel services, so "
    r"$397$ CYP is a lower bound on protection and the \$113 cost per CYP an upper bound. \textit{Panel C} "
    r"is an illustrative scenario, not a measured outcome: a counselor-month delivers $54.1$ sessions at "
    r"\$288.33, and the IV dose reductions on total sessions (Table~\ref{tab:iv_mechanism}) raise the women "
    r"served at fixed capacity; the cost row is counselor salary only, part of the \$43.85 full cost per "
    r"treated woman. $^{**}$ p$<$0.05.")
o.append(r"\end{minipage}")
o.append(r"\end{table}")

text = "\n".join(o) + "\n"
for p in OUTS:
    with open(os.path.abspath(p), "w") as fh:
        fh.write(text)
    print("Wrote", os.path.abspath(p))
